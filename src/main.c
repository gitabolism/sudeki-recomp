/**
 * Sudeki - Recompiled Game Entry Point (Linux host, Windows path kept)
 *
 * Adapted from xboxrecomp/templates/new-game/src/main.c. The boot order is
 * the template's, unchanged:
 *
 * 1. Load the original XBE file from disk
 * 2. Initialize the Xbox memory layout (map data sections to original VAs)
 * 3. Bring up the emulated APU when RECOMP_AC97_READY is set
 * 4. Initialize the Xbox kernel replacement layer
 * 5. Set up game file paths for I/O redirection
 * 6. Initialize the kernel bridge (thunk table in Xbox memory)
 * 7. Set the stack pointer
 * 8. Install the crash handler (VEH on Windows, sigaction on POSIX)
 * 9. Build the dispatch table, arm the watchdog
 * 10. Call the game's original entry point (recompiled)
 *
 * XBE details (verified against the pinned digest, see THIRD_PARTY.md):
 *   Title:       Sudeki
 *   Title ID:    0x4D53000A
 *   Base addr:   0x00010000
 *   Entry point: 0x0026C703
 *   XDK:         5849 (links D3D8LTCG, XGRAPHCL)
 *   XBE built:   2004-06-26 18:00:49 UTC
 *   Image size:  4,288,384 bytes; .text 0x27424C; 34 sections
 *   Kernel imports: 119 ordinals
 *   default.xbe SHA-256: 1e28c3db033a3de471ba78ccdd13a824ebddd17fdd0479bf69a795f63bd92419
 */

